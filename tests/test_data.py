"""Проверки данных. Каждый тест краснеет ровно на одном виде порчи."""

from data import _rows_from_csv, check_rows


def rows(*pairs: tuple[str, str]) -> list[dict]:
    return [{"Месяц": name, "Выручка": value} for name, value in pairs]


def test_чистые_данные_не_дают_замечаний():
    problems = check_rows(
        rows(("Январь", "100"), ("Февраль", "110"), ("Март", "105")),
        "Месяц",
        ["Выручка"],
    )
    assert problems == []


def test_пустая_таблица():
    assert check_rows([], "Месяц", ["Выручка"]) == ["Таблица пустая — читать нечего."]


def test_выброс_находится():
    problems = check_rows(
        rows(("Январь", "100"), ("Февраль", "110"), ("Март", "99999999")),
        "Месяц",
        ["Выручка"],
    )
    assert len(problems) == 1
    assert "Март" in problems[0]
    assert "лишние нули" in problems[0]


def test_значение_чуть_выше_остальных_не_выброс():
    """Порог 50. Втрое больше — это просто хороший месяц, а не опечатка."""
    problems = check_rows(
        rows(("Январь", "100"), ("Февраль", "110"), ("Март", "300")),
        "Месяц",
        ["Выручка"],
    )
    assert problems == []


# Две проверки ниже держат сам порог. Без них тест на выброс проходил бы
# даже при пороге 500 000: значение 99999999 пролезает через любой.
def test_чуть_ниже_порога_не_выброс():
    """Медиана 110, порог 50 — граница 5500. 4400 остаётся нормой."""
    problems = check_rows(
        rows(("Январь", "100"), ("Февраль", "110"), ("Март", "4400")),
        "Месяц",
        ["Выручка"],
    )
    assert problems == []


def test_чуть_выше_порога_уже_выброс():
    """6600 — это 60 медиан, порог перейдён."""
    problems = check_rows(
        rows(("Январь", "100"), ("Февраль", "110"), ("Март", "6600")),
        "Месяц",
        ["Выручка"],
    )
    assert len(problems) == 1
    assert "Март" in problems[0]


def test_текст_вместо_числа():
    problems = check_rows(
        rows(("Январь", "сто"), ("Февраль", "110"), ("Март", "105")),
        "Месяц",
        ["Выручка"],
    )
    assert problems == ["«Январь»: «сто» в «Выручка» — не число."]


def test_пустая_ячейка():
    problems = check_rows(
        rows(("Январь", ""), ("Февраль", "110"), ("Март", "105")),
        "Месяц",
        ["Выручка"],
    )
    assert problems == ["«Январь»: пустое значение в «Выручка»."]


def test_повтор_месяца():
    problems = check_rows(
        rows(("Январь", "100"), ("Январь", "110"), ("Март", "105")),
        "Месяц",
        ["Выручка"],
    )
    assert problems == ["«Январь» встречается больше одного раза."]


def test_строка_без_названия():
    problems = check_rows(
        rows(("", "100"), ("Февраль", "110"), ("Март", "105")),
        "Месяц",
        ["Выручка"],
    )
    assert problems == ["Есть строка без значения в «Месяц»."]


def test_меньше_трёх_строк_выбросы_не_ищем():
    """На двух точках медиана бессмысленна — любая пара выглядит выбросом."""
    problems = check_rows(rows(("Январь", "1"), ("Февраль", "999999")), "Месяц", ["Выручка"])
    assert problems == []


def test_пробелы_по_краям_обрезаются():
    """В таблицах пробелы набивают руками и не замечают."""
    parsed = _rows_from_csv(" Месяц , Выручка \nАпрель ,  502000 \n")
    assert parsed == [{"Месяц": "Апрель", "Выручка": "502000"}]
